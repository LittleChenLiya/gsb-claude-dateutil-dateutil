# -*- coding: utf-8 -*-
"""
Schedule adapter
================

:class:`Schedule` adapts a *local* :class:`~dateutil.rrule.rrule` -- a
recurrence rule whose occurrences are naive wall-clock datetimes -- into an
ordered, de-duplicated sequence of UTC instants over a UTC half-open
interval.

The recurrence candidates are generated by :mod:`dateutil.rrule`; this
module only localizes them to a time zone and resolves the two pathological
wall-clock situations that raw recurrence rules cannot express:

* **Imaginary times** -- wall-clock times that do not exist because the
  local standard time jumped forward (e.g. ``02:30`` on the spring-forward
  day in America/New_York).  These can either be skipped
  (:data:`SKIP`) or shifted forward to a valid instant (:data:`SHIFT`).
* **Ambiguous times** -- wall-clock times that occur twice because the
  local standard time fell back (e.g. ``01:30`` on the fall-back day in
  America/New_York).  The earlier offset (:data:`EARLIER`), the later
  offset (:data:`LATER`) or both (:data:`BOTH`) can be selected.

All filtering is done in UTC over the half-open interval ``[start, end)``,
so the second occurrence of an ambiguous time is never dropped by a
wall-clock comparison, and the returned instants are guaranteed to be
unique and ordered.
"""

from datetime import timedelta

from dateutil.rrule import rrulebase
from dateutil.tz import (
    UTC,
    datetime_ambiguous,
    datetime_exists,
    enfold,
    resolve_imaginary,
)

__all__ = ["Schedule", "SKIP", "SHIFT", "EARLIER", "LATER", "BOTH"]

# Strategies for imaginary (nonexistent) wall-clock times.
SKIP = "skip"
SHIFT = "shift"

# Strategies for ambiguous (repeated) wall-clock times.
EARLIER = "earlier"
LATER = "later"
BOTH = "both"

# A margin wide enough to cover any real-world UTC offset when translating
# the UTC selection window into naive wall-clock bounds for the rule.
_WALL_MARGIN = timedelta(days=2)


def _as_utc(dt):
    """Return ``dt`` as an aware datetime in UTC (naive == UTC)."""
    if dt.tzinfo is None:
        return dt.replace(tzinfo=UTC)
    return dt.astimezone(UTC)


class Schedule(object):
    """
    An adapter turning a local recurrence rule into UTC instants.

    :param rule:
        A :class:`~dateutil.rrule.rrule` (or
        :class:`~dateutil.rrule.rruleset`) generating naive wall-clock
        :class:`~datetime.datetime` candidates.  The rule's calendar logic
        is used as-is; it is never rewritten.

    :param tz:
        A time zone, as a :class:`datetime.tzinfo` object (e.g. the result
        of :func:`dateutil.tz.gettz`).

    :param nonexistent:
        What to do with wall-clock times that do not exist in ``tz``
        (spring-forward gaps).  One of :data:`SKIP` (the candidate is
        dropped) or :data:`SHIFT` (the candidate is moved forward to the
        first valid instant, per :func:`dateutil.tz.resolve_imaginary`).
        Defaults to :data:`SKIP`.

    :param ambiguous:
        What to do with wall-clock times that occur twice in ``tz``
        (fall-back overlaps).  One of :data:`EARLIER` (fold 0, DST side),
        :data:`LATER` (fold 1, standard side) or :data:`BOTH` (both
        instants).  Defaults to :data:`EARLIER`.
    """

    def __init__(self, rule, tz, nonexistent=SKIP, ambiguous=EARLIER):
        if not isinstance(rule, rrulebase):
            raise TypeError("rule must be an rrule or rruleset")
        if tz is None:
            raise ValueError("a time zone is required")

        # The adapter works on naive wall-clock candidates; attaching the
        # zone is this module's job.
        rules = getattr(rule, "_rrule", None)
        if rules is None:
            rules = [rule]
        for rr in rules:
            if rr._dtstart is not None and rr._dtstart.tzinfo is not None:
                raise ValueError(
                    "rule must generate naive wall-clock datetimes; "
                    "got aware dtstart %r" % (rr._dtstart,)
                )

        if nonexistent not in (SKIP, SHIFT):
            raise ValueError(
                "nonexistent must be one of SKIP or SHIFT, got %r"
                % (nonexistent,)
            )
        if ambiguous not in (EARLIER, LATER, BOTH):
            raise ValueError(
                "ambiguous must be one of EARLIER, LATER or BOTH, got %r"
                % (ambiguous,)
            )

        self._rule = rule
        self._tz = tz
        self._nonexistent = nonexistent
        self._ambiguous = ambiguous

    # ------------------------------------------------------------------
    # Localization: one naive wall-clock candidate -> 0, 1 or 2 UTC
    # instants, depending on the DST situation and the chosen strategies.
    # ------------------------------------------------------------------
    def _localize(self, wall):
        """Return the UTC instant(s) for a naive wall-clock candidate."""
        if not datetime_exists(wall, self._tz):
            # Imaginary time: the wall clock jumped over this value.
            if self._nonexistent == SKIP:
                return ()
            # SHIFT: resolve_imaginary moves the wall clock forward by the
            # transition's offset change to the first valid instant.
            shifted = resolve_imaginary(wall.replace(tzinfo=self._tz))
            return (shifted.astimezone(UTC),)

        if datetime_ambiguous(wall, self._tz):
            # Ambiguous time: the same wall clock occurs twice.
            if self._ambiguous == EARLIER:
                folds = (0,)
            elif self._ambiguous == LATER:
                folds = (1,)
            else:  # BOTH
                folds = (0, 1)

            instants = []
            for fold in folds:
                local = enfold(wall, fold=fold).replace(tzinfo=self._tz)
                instants.append(local.astimezone(UTC))
            return tuple(instants)

        # A regular, unambiguous wall-clock time.
        return (wall.replace(tzinfo=self._tz).astimezone(UTC),)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------
    def between(self, start, end):
        """
        Return the schedule's UTC instants in the half-open interval
        ``[start, end)``.

        ``start`` and ``end`` are expressed in UTC: aware datetimes are
        converted to UTC, naive datetimes are assumed to be UTC.  The
        interval is half-open -- the start instant is included, the end
        instant is excluded -- and the filtering is performed on the
        localized UTC instants, never on the wall clock, so the second
        occurrence of an ambiguous time is not lost.

        The returned list is ordered and contains no duplicate instants
        (a shifted imaginary time may land on top of another candidate).
        """
        start_utc = _as_utc(start)
        end_utc = _as_utc(end)
        if end_utc < start_utc:
            raise ValueError("end must not precede start")

        # Translate the UTC selection window into naive wall-clock bounds
        # for the rule.  The margin keeps DST transitions from clipping
        # candidates that belong to the requested UTC range.
        wall_lo = (start_utc - _WALL_MARGIN).astimezone(self._tz)
        wall_hi = (end_utc + _WALL_MARGIN).astimezone(self._tz)
        wall_lo = wall_lo.replace(tzinfo=None)
        wall_hi = wall_hi.replace(tzinfo=None)

        instants = set()
        for wall in self._rule.between(wall_lo, wall_hi, inc=True):
            for instant in self._localize(wall):
                if start_utc <= instant < end_utc:
                    instants.add(instant)

        return sorted(instants)

    def __iter__(self):
        """
        Iterate over all UTC instants of the schedule.

        .. warning::
            Rules without a finite ``COUNT`` or ``UNTIL`` generate an
            unbounded number of candidates; prefer :meth:`between` with an
            explicit UTC range for those.
        """
        for wall in self._rule:
            for instant in self._localize(wall):
                yield instant
